"""Retained-byte verification and compact publication for a complete bank."""
import argparse
import gzip
import json
from pathlib import Path
import shutil
import shlex
import subprocess

from encoder_atoms import read,save,sha
from publish_context_statistics import checked_collection
from publish_source_context import REMOTE


def verify(root):
    root=Path(root).resolve();c,j,r=checked_collection(root);base=j['result']['diagnostics']['cwd'];p=root/'result'
    seal=read(p/'prediction-seal.json');ref=read(p/'reference-receipt.json');model=ref['parameters']['source'];weight=model['weightFile']
    weight_path=str(Path(model['modelRoot'])/weight['path']);config_path=model['modelRoot']+'/text_encoder/config.json'
    items=[*seal['rows'],*[z['port'] for z in seal['rows']],*seal['states'],seal['asset'],seal['interfaces'],*ref['rows'],
        {'path':weight_path,'sha256':weight['sha256']},{'path':config_path,'sha256':model['assets']['text_encoder/config.json']},
        {'path':base+'/source-ids.npy','sha256':sha(p/'source-ids.npy')},
        {'path':base+'/compiled/compile-receipt.json','sha256':sha(p/'compile-receipt.json')}]
    for name in ['reference-receipt.json','prediction-seal.json','report.json','linear-head-effects.json']:
        items.append({'path':base+'/response-result/'+name,'sha256':sha(p/name)})
    result=subprocess.run(['ssh','-T','-o','BatchMode=yes','-o','ConnectTimeout=15','beast','python3 -c '+shlex.quote(REMOTE)],
        input=json.dumps({'allowedRoots':[base,weight_path,config_path],'items':items}),text=True,capture_output=True,check=True,timeout=240)
    value=json.loads(result.stdout);value.update(schema='tce-complete-bank-retained-bytes-v1',jobID=j['job_id'],predictionSealSHA256=sha(p/'prediction-seal.json'),
        verifierSourceSHA256=sha(__file__),sharedRemoteVerifierSHA256=sha(Path(__file__).parent/'publish_source_context.py'),
        scope='Authenticated remote full-byte hashing of complete candidate banks, ports, all final head moment states, source assets and consumer arrays. Includes original checkpoint/config; not all newly generated bytes. No local array hydration.')
    save(root/'retained-array-verification.json',value)
    return {'files':len(value['files']),'bytes':value['totalBytesVerified']}


def publish(root,destination):
    root=Path(root).resolve();c,j,r=checked_collection(root);p=root/'result';v=read(root/'retained-array-verification.json')
    if v['predictionSealSHA256']!=sha(p/'prediction-seal.json') or v['verifierSourceSHA256']!=sha(__file__) or v['sharedRemoteVerifierSHA256']!=sha(Path(__file__).parent/'publish_source_context.py'):raise ValueError('Verification differs')
    out=Path(destination).resolve();out.mkdir(parents=True,exist_ok=False);transforms=[]
    for path in p.iterdir():
        if not path.is_file():raise ValueError('Unexpected result directory')
        if path.suffix=='.jsonl':
            data=path.read_bytes();target=out/(path.name+'.gz');target.write_bytes(gzip.compress(data,compresslevel=9,mtime=0))
            if gzip.decompress(target.read_bytes())!=data:raise ValueError('Lossless stream differs')
            transforms.append({'source':path.name,'sourceBytes':len(data),'sourceSHA256':sha(path),'published':target.name,
                'publishedBytes':target.stat().st_size,'publishedSHA256':sha(target)})
        else:shutil.copyfile(path,out/path.name)
    shutil.copyfile(root/'retained-array-verification.json',out/'retained-array-verification.json')
    save(out/'provenance.json',{'schema':'tce-complete-bank-public-v1','jobID':j['job_id'],'requestSHA256':r['requestSHA256'],
        'payloadCustody':c['custody'],'schedulerResult':c['result'],'completeCollectedInventory':c['inventory'],'losslessStreamTransports':transforms,
        'remoteResultRoot':j['result']['diagnostics']['cwd']+'/response-result',
        'publication':'All compact results preserved. Full prediction banks, final moment states, source asset and original-consumer arrays stay near compute with independent byte verification.',
        'claimBoundary':'All32heads predicted from rawtext without reference-head refresh. Original learned fullblock consumer and exact references evaluated offline after seal; not completeencoder or strictzero-neural images.'})
    save(out/'files.json',{path.name:sha(path) for path in out.iterdir()})
    return {'files':len(list(out.iterdir())),'bytes':sum(path.stat().st_size for path in out.iterdir())}


if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('action',choices=['verify','publish']);p.add_argument('run');p.add_argument('destination',nargs='?');a=p.parse_args()
    print(verify(a.run) if a.action=='verify' else publish(a.run,a.destination))
